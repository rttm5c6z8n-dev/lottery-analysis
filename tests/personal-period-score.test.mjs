import assert from 'node:assert/strict';
import{buildFiveRecords}from '../personal/v40-core.mjs';
import{prepareEvidence,applyEvidence}from '../personal/v42-core.mjs';
import{scoreByDraw}from '../personal/period-score.mjs';
const model={id:'archived',version:'v31',generatedAt:'2026-11-10T00:00:00Z',throughPeriod:'26128',picks:Array.from({length:5},(_,i)=>({nums:[i+1,i+6,i+11,i+16,i+21,6,7]}))};
const base={results:[model],resultId:'archived',now:'2026-11-11T00:00:00Z',drawAt:'2026-11-14T20:30:00+08:00',sourceUrl:'https://www.sport.gov.cn/test'};
const a=buildFiveRecords({...base,period:'26135'});
const b=buildFiveRecords({...base,period:'26136'});
const evidence=(period)=>prepareEvidence({period,numbers:'1 2 3 4 5 6 7',url:'https://www.sport.gov.cn/test',title:'测试公告',observedAt:'2026-11-15T00:00:00Z'});
const verified=[...applyEvidence(a,evidence('26135')).records,...applyEvidence(b,evidence('26136')).records];
const outcome=scoreByDraw(verified);
assert.equal(outcome.periods,2);
assert.equal(outcome.tickets,10);
assert.equal(outcome.draws.length,2);
assert.equal(outcome.draws[0].tickets,5);
assert.equal(outcome.baselineExpectedExact,10/21425712);
assert.equal(outcome.issues.length,0);
const mixed=scoreByDraw([...verified, {period:'26137',ticket:{front:[1,2,3,4,5],back:[6,7]},createdAt:'2026-11-10T00:00:00Z',verification:null}]);
assert.equal(mixed.periods,2);
assert.equal(mixed.tickets,10);
assert.equal(scoreByDraw([]).periods,0);
console.log('Per-period scoreboard tests passed');
