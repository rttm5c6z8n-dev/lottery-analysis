import assert from 'node:assert/strict';
import{validateReceiptRequest,validateReceiptData}from '../personal/v40-server-receipt-core.mjs';
const sample={period:'26130',digest:'c'.repeat(64),scope:'five-tickets',plannedDrawAt:'2026-11-14T20:30:00+08:00'};
const latest={period:'26129',date:'2026-11-11'};
const now='2026-11-12T02:00:00Z';
const value=validateReceiptRequest(sample,latest,now);
assert.equal(value.period,'26130');
assert.equal(value.latestOfficialPeriod,'26129');
assert.throws(()=>validateReceiptRequest({...sample,period:'26129'},latest,now),/不是官方/);
assert.throws(()=>validateReceiptRequest({...sample,period:'26131'},latest,now),/不是官方/);
assert.throws(()=>validateReceiptRequest({...sample,digest:'bad'},latest,now),/SHA-256/);
assert.throws(()=>validateReceiptRequest({...sample,scope:'ten-tickets'},latest,now),/锁定注数/);
assert.throws(()=>validateReceiptRequest({...sample,plannedDrawAt:'2026-11-14T20:30:00Z'},latest,now),/北京时间/);
assert.throws(()=>validateReceiptRequest({...sample,plannedDrawAt:'2026-11-16T20:30:00+08:00'},latest,now),/常规日期/);
assert.throws(()=>validateReceiptRequest(sample,latest,'2026-11-14T12:29:30Z'),/不到一分钟/);
assert.throws(()=>validateReceiptRequest(sample,latest,'2026-11-14T13:00:00Z'),/已经到达/);
const stored=validateReceiptData({id:'598c5f8c-24a1-4c62-86ef-cac096b93a57',period:'26130',digest:sample.digest,scope:'five-tickets',planned_draw_at:sample.plannedDrawAt,received_at:'2026-11-12T02:00:00Z',latest_official_period:'26129',latest_official_date:'2026-11-11',source_url:'https://www.gstc.org.cn/wanfa/dlt_history'});
assert.equal(stored.receivedAt,'2026-11-12T02:00:00Z');
assert.equal(stored.digest,sample.digest);
assert.throws(()=>validateReceiptData({...stored,digest:'xyz'}),/无效回执/);
console.log('D1 timestamped SHA-256 receipt validation passed');
