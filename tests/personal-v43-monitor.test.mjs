import assert from 'node:assert/strict';
import{buildProspectiveMonitor}from '../personal/v43-monitor-core.mjs';
const ticket={front:[2,7,25,26,31],back:[5,9]};
const item={period:'26129',ticket,createdAt:'2026-11-11T15:00:00+08:00',source:{type:'v31-result',rank:1,throughPeriod:'26128',generatedAt:'2026-11-11T14:32:54+08:00'},targetEvidence:{plannedDrawAt:'2026-11-11T20:30:00+08:00',sourceUrl:'https://www.gstc.org.cn/notice'}};
const draw={period:'26129',date:'2026-11-11',front:[2,12,14,17,33],back:[7,8]};
const official={latestPeriod:'26129',crossPageAgreement:true,records:[draw]};
const r=buildProspectiveMonitor([item,{...item,source:{...item.source,rank:2}}, {...item,period:'26130',source:{...item.source,rank:3}}],official);
assert.equal(r.periods,2);
assert.equal(r.storedTickets,3);
assert.equal(r.periodsWithOfficialData,1);
assert.equal(r.rows[1].period,'26129');
assert.equal(r.rows[1].storedTickets,2);
assert.equal(r.rows[1].eligibleTickets,2);
assert.equal(r.rows[1].bestFront,1);
assert.equal(r.rows[1].exactTickets,0);
assert.equal(r.rows[1].sourceCorroborated,true);
assert.equal(r.rows[0].sourceCorroborated,false);
assert.equal(r.rows[0].officialDraw,null);
assert.equal(buildProspectiveMonitor([item],{...official,crossPageAgreement:false}).rows[0].sourceCorroborated,false);
assert.equal(buildProspectiveMonitor([{...item,createdAt:'2026-11-11T21:00:00+08:00'}],official).rows[0].eligibleTickets,0);
assert.equal(buildProspectiveMonitor([{...item,source:{...item.source,throughPeriod:'26129'}}],official).rows[0].eligibleTickets,0);
assert.equal(buildProspectiveMonitor([null],official).unsafeRecords,1);
assert.deepEqual(buildProspectiveMonitor([],official).rows,[]);
const wrong={...item,verification:{draw:{front:[1,2,3,4,5],back:[1,2]},result:{frontHits:5,backHits:2,exact:true}}};
assert.equal(buildProspectiveMonitor([wrong],official).rows[0].eligibleTickets,0);
assert.throws(()=>buildProspectiveMonitor('wrong',official),/不是数组/);
const badProof=buildProspectiveMonitor([item],official,new Set(['26129']));
assert.equal(badProof.rows[0].eligibleTickets,0);
assert.match(badProof.rows[0].sourceStatus,/指纹校验失败/);
assert.deepEqual(badProof.invalidProofPeriods,['26129']);
console.log('V4.3 prospective read-only monitoring tests passed');
