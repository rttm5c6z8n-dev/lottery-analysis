import assert from 'node:assert/strict';
import{onRequestGet,onRequestPost}from '../functions/api/lock-receipts.js';
const base='https://lottery-analysis.pages.dev/api/lock-receipts';
const uuid='598c5f8c-24a1-4c62-86ef-cac096b93a57';
const row={id:uuid,period:'26130',digest:'c'.repeat(64),scope:'five-tickets',planned_draw_at:'2026-11-14T20:30:00+08:00',received_at:'2026-11-12T02:00:00Z',latest_official_period:'26129',latest_official_date:'2026-11-11',source_url:'https://www.gstc.org.cn/wanfa/dlt_history'};
const get=new Request(base+'?id='+uuid);
const missing=await onRequestGet({request:get,env:{}});
assert.equal(missing.status,503);
assert.equal((await missing.json()).code,'STORAGE_NOT_CONFIGURED');
const fakeDb={prepare(query){assert.match(query,/SELECT/);return{bind(id){assert.equal(id,uuid);return{first:async()=>row}}}}};
const read=await onRequestGet({request:get,env:{LOCK_DB:fakeDb}});
assert.equal(read.status,200);
assert.equal((await read.json()).receipt.digest,row.digest);
const invalid=await onRequestGet({request:new Request(base+'?id=bad'),env:{LOCK_DB:fakeDb}});
assert.equal(invalid.status,400);
const foreign=await onRequestGet({request:new Request(base+'?id='+uuid,{headers:{Origin:'https://evil.invalid'}}),env:{LOCK_DB:fakeDb}});
assert.equal(foreign.status,403);
const post=await onRequestPost({request:new Request(base,{method:'POST',headers:{'content-type':'application/json'},body:'{}'}),env:{}});
assert.equal(post.status,503);
assert.equal((await post.json()).persisted,undefined);
console.log('Lock receipt API: no DB fail-closed, later GET, invalid ID and cross-origin checks passed');
