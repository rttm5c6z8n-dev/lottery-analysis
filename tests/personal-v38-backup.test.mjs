import assert from 'node:assert/strict';
import{buildRecord,parseDraw,verifyRecord}from '../personal/v38-core.mjs';
import{makeBackup,mergeBackup}from '../personal/v38-backup.mjs';
const a=buildRecord({period:'26135',front:'1 2 3 4 5',back:'6 7',method:'test',createdAt:'2026-11-11T00:00:00Z'});
const b=buildRecord({period:'26136',front:'5 8 9 10 11',back:'3 4',method:'test2',createdAt:'2026-11-12T00:00:00Z'});
const checked=verifyRecord(b,parseDraw('05 08 09 10 11 03 04'),'2026-11-13T00:00:00Z');
const backup=makeBackup([a,checked],'2026-11-14T00:00:00Z');
const restored=mergeBackup([a],backup);
assert.equal(restored.added,1);
assert.equal(restored.skipped,1);
assert.equal(restored.records[0],a);
assert.equal(restored.records[1].verification.result.exact,true);
assert.equal(mergeBackup(restored.records,backup).added,0);
assert.throws(()=>mergeBackup([], {records:[a,a]}),/重复/);
const tampered=structuredClone(checked);tampered.verification.result.frontHits=2;
assert.throws(()=>mergeBackup([a],{records:[tampered]}),/不一致/);
assert.throws(()=>mergeBackup([a],{records:[a,tampered]}),/不一致/);
assert.throws(()=>mergeBackup(null,backup),/本机记录损坏/);
assert.throws(()=>mergeBackup([a],{records:null}),/不是预测记录备份/);
console.log('V3.8 backup tests passed');
