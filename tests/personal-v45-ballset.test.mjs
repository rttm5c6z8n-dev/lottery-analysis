import assert from 'node:assert/strict';
import{parseMachineBulletin,summarizeBallSetMetadata}from '../personal/v45-ballset-core.mjs';
const source='https://api.js-lottery.com/cms/post-148233.html';
const sample='<h1>中国体育彩票超级大乐透第26129期开奖公告</h1><p>开奖日期：2026年11月11日</p><p>本期使用第2套摇奖球</p><table><tr><td>本期出球顺序：</td><td>02 12 14 33 17</td><td>08 07</td></tr><tr><td>本期开奖号码：</td><td>02 12 14 17 33</td><td>07 08</td></tr></table><h2>本期中奖情况</h2>';
const result=parseMachineBulletin(sample,'26129',source);
assert.equal(result.period,'26129');
assert.equal(result.ballSet,2);
assert.deepEqual(result.drawOrder.front,[2,12,14,33,17]);
assert.deepEqual(result.drawOrder.back,[8,7]);
assert.deepEqual(result.numbers.front,[2,12,14,17,33]);
assert.equal(result.date,'2026-11-11');
assert.equal(result.source,source);
assert.throws(()=>parseMachineBulletin(sample,'26128',source),/期号与请求不一致/);
assert.throws(()=>parseMachineBulletin(sample.replace('第2套','第4套'),'26129',source),/未披露/);
assert.throws(()=>parseMachineBulletin(sample.replace('02 12 14 33 17','02 12 14 33 18'),'26129',source),/顺序与官方开奖号码不一致/);
const doc2026='<h1>第26014期开奖结果公告</h1>开奖日期：2026年2月2日 本期使用第2套摇奖球 前区 后区 本期出球顺序：34 18 23 35 16 06 01 本期开奖号码：16 18 23 34 35 01 06 本期中奖情况';
assert.equal(parseMachineBulletin(doc2026,'26014','https://www.gdlottery.cn/f_html/kjgg/P085_26014.html').ballSet,2);
const counts=summarizeBallSetMetadata([result,{...result,period:'26128',ballSet:3},result]);
assert.deepEqual(counts.map(x=>x.issues),[0,1,1]);
assert.equal(counts.every(x=>x.enoughForExploratoryFrequency===false),true);
console.log('Official machine ball-set and ordered draw parser: strict draw reconciliation, sample coverage PASS');
