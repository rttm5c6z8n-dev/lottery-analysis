import assert from 'node:assert/strict';
import{buildFiveRecords,appendFiveRecords}from '../personal/v40-core.mjs';
import{prepareEvidence,applyEvidence}from '../personal/v42-core.mjs';
import{auditJournal}from '../personal/v41-core.mjs';
import{makeBackup,mergeBackup}from '../personal/v38-backup.mjs';
const model={id:'archived-1',snapshotId:'snap1',trainId:'train1',reportId:'report1',generatedAt:'2026-11-11T01:00:00Z',throughPeriod:'26128',version:'BC-exhaustive-3.1',picks:Array.from({length:5},(_,i)=>({nums:[1+i,6+i,11+i,16+i,21+i,6,7],score:10-i}))};
const input={results:[model],resultId:'archived-1',period:'26135',now:'2026-11-11T03:00:00Z',drawAt:'2026-11-14T20:30:00+08:00',sourceUrl:'https://www.sport.gov.cn/notice'};
const predictions=appendFiveRecords([],buildFiveRecords(input));
assert.equal(predictions.length,5);
assert.deepEqual(predictions.map(r=>r.source.rank),[1,2,3,4,5]);
const file=makeBackup(predictions,'2026-11-11T04:00:00Z');
assert.equal(mergeBackup([],file).added,5);
const evidence=prepareEvidence({period:'26135',numbers:'01 02 03 04 05 06 07',url:'https://www.sport.gov.cn/notice',title:'测试用模拟公告',observedAt:'2026-11-15T00:00:00Z'});
const verified=applyEvidence(predictions,evidence);
assert.equal(verified.matched,5);
assert.equal(verified.records.filter(r=>r.verification).length,5);
const audited=auditJournal(verified.records);
assert.equal(audited.stats.verified,5);
assert.equal(audited.stats.prospectiveEligible,5);
assert.equal(audited.stats.confirmedOfficial,0);
assert.equal(audited.issues.length,0);
assert.equal(new Set(verified.records.map(r=>r.period)).size,1);
assert.throws(()=>appendFiveRecords(verified.records,buildFiveRecords(input)),/已有预测留档/);
assert.throws(()=>applyEvidence(verified.records,evidence),/已核验/);
console.log('Five tickets, one period: lock → backup → verify → audit test passed');
