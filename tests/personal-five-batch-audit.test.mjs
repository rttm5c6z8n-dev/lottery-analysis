import assert from 'node:assert/strict';
import{auditMarkedBatches}from '../personal/five-batch-audit.mjs';
import{buildFiveRecords,appendFiveRecords}from '../personal/v40-core.mjs';
import{auditJournal}from '../personal/v41-core.mjs';
import{buildProspectiveMonitor}from '../personal/v43-monitor-core.mjs';
const model={id:'arch',generatedAt:'2026-11-11T01:00:00Z',throughPeriod:'26128',version:'v3.1',picks:Array.from({length:5},(_,i)=>({nums:[1+i,6+i,11+i,16+i,21+i,6,7]}))};
const input={results:[model],resultId:'arch',period:'26130',now:'2026-11-12T00:00:00Z',drawAt:'2026-11-14T20:30:00+08:00',sourceUrl:'https://www.sport.gov.cn/notice'};
const batch=appendFiveRecords([],buildFiveRecords(input));
assert.equal(batch.length,5);
assert.equal(auditMarkedBatches(batch).issues.length,0);
assert.equal(auditJournal(batch).issues.length,0);
const partial=batch.slice(0,4);
assert.equal(auditMarkedBatches(partial).invalidIndices.size,4);
assert.equal(auditJournal(partial).valid.length,0);
const altered=batch.map((r,i)=>i===2?{...r,batch:{...r.batch,rank:1}}:r);
assert.equal(auditMarkedBatches(altered).invalidIndices.size,5);
const mixed=[...batch,{...batch[0],batch:undefined,source:{...batch[0].source,rank:1}}];
assert.equal(auditMarkedBatches(mixed).invalidIndices.size,6);
const official={latestPeriod:'26129',crossPageAgreement:true,records:[{period:'26129',date:'2026-11-11',front:[2,12,14,17,33],back:[7,8]}]};
const report=buildProspectiveMonitor(partial,official);
assert.equal(report.rows[0].eligibleTickets,0);
assert.equal(report.batchIssues.length,1);
assert.equal(buildProspectiveMonitor(batch,official).rows[0].eligibleTickets,5);
const legacy=[{...batch[0],batch:undefined}];
assert.equal(auditMarkedBatches(legacy).issues.length,0);
console.log('Five batch integrity, legacy compatibility and monitor exclusion passed');
